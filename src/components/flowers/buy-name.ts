/**
 * 도감 상세의 「사러 가기」가 검색어로 쓰는 **대표 이름**.
 *
 * ── 왜 이 함수가 여기 또 있나 (Advisor 판단 대기) ────────────────────
 * 결과 화면에도 **글자 그대로 같은 규칙**이 있다(`components/flow/ResultView.tsx` 의
 * `mainName`). 그쪽은 모듈 바깥으로 내보내지 않는 파일 내부 함수라 가져다 쓸 길이 없고,
 * 이 라운드에서 `flow/` 는 다른 사람이 쥐고 있어 export 를 늘릴 수도 없었다.
 * 그래서 규칙을 이쪽 소유로 한 벌 세운다 — **베낀 것이 아니라 같은 사실을 두 화면이
 * 각자 아는 상태**다. 합칠 자리가 생기면 `flow/buy-links.ts` 옆으로 올리는 것이 맞다
 * (그 파일이 이미 검색어 규칙의 원본이고, 두 화면이 함께 import 한다).
 * ⚠ 한쪽만 고치지 마라. `tests/components/flowers-buy.test.ts` 가 두 규칙이 같은 답을
 *   내는지 소스로 맞대어 본다.
 *
 * ── 규칙 (실측 근거는 `docs/partners-research.md` §5) ─────────────────
 * 두 가지를 떼어 낸다. 둘 다 **검색 결과를 좁히기만** 하기 때문이다:
 *   · 괄호 속 딴이름 — `미모사(은엽아카시아)` 를 그대로 넣으면 걸리는 것이 없다
 *   · 앞에 붙은 색·품종 수식 — `빨간 장미 꽃배달` 은 0건이고 `장미 꽃배달` 은 12건이다
 * 한 낱말짜리 이름(`수국` `프리지아`)은 그대로 돌려준다.
 *
 * 이름 목록을 여기 적어 두지 않는 이유도 그쪽과 같다 — `content/flowers.csv` 는 계속
 * 자란다(2026-08-17 하루에 47종 → 59종). 규칙만 두면 새 꽃이 저절로 따라온다.
 */
export function buySearchName(nameKo: string): string {
  const parts = nameKo
    .replace(/\([^)]*\)/g, ' ')
    .trim()
    .split(/\s+/);

  return parts[parts.length - 1] || nameKo;
}
