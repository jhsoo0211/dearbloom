/**
 * 비밀 편지 화면의 문구 — **기기 저장 단계에서 화면이 말해야 하는 것** (design-spec §1.5o).
 *
 * ── 왜 문구를 한곳에 모았나 ──────────────────────────────────────────
 * 2026-08-17 감사가 P0 으로 올린 것은 버그가 아니라 **거짓말**이었다. 화면은 "번호를 아는
 * 분만 그 편지를 열 수 있어요" 라고 말했지만, 편지는 만든 사람의 브라우저에만 있어서
 * 받는 사람 기기에서는 올바른 번호를 넣어도 열리지 않는다. 실패하면 "한 글자씩 다시 봐
 * 주시겠어요?" 라며 오타를 의심시키고, 다섯 번 어긋나면 20초를 기다리게 했다.
 * 구조적으로 불가능한 일을 사용자 탓으로 돌린 셈이다.
 *
 * 그 문장들이 세 파일(입구·스튜디오·라우트 페이지)에 흩어져 있었기 때문에 한 자리를 고쳐도
 * 나머지가 옛말을 계속했다. 그래서 여기 모은다 — **화면마다 새로 짓지 않는다**
 * (`src/components/flowers/birth-copy.ts` 와 같은 장치다).
 *
 * ── 서버 저장으로 넘어가는 날 ────────────────────────────────────────
 * `SupabaseLetterStore` 를 끼우는 순간 이 파일의 문장은 **먼저 거짓이 된다.** 저장소를
 * 갈아 끼우기 전에 여기부터 고쳐라. 아래 문장들은 "지금 이 단계의 사실"이지 서비스의
 * 약속이 아니다(`/partners` 의 `NO_AFFILIATION` 과 같은 성격의 상수다).
 * `tests/letters/device-notice.test.ts` 가 이 선을 지킨다.
 *
 * ⚠ 문구에 개발 어휘를 들이지 마라(§1.5d 해요체·이야기 톤). `브라우저 저장소` 까지가
 *   지금 쓰는 결이고, 그 아래(`localStorage`·`API`·`Supabase`)로는 내려가지 않는다.
 */

