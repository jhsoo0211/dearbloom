/* ------------------------------------------------------------------ *
 * 한 벌의 모양
 * ------------------------------------------------------------------ */

/** 저장 방식에 따라 갈리는 문구 한 벌. 두 벌이 **같은 칸을 모두** 채운다. */
export interface LetterStorageCopy {
  /** 고지 — 편지가 어디에 남는지. 강조 한 줄 + 본문. */
  notice: { lead: string; body: string };
  /** 위 둘을 이어 붙인 한 문장(메타데이터·푸터가 쓴다). */
  noticeText: string;
  /** 편지 열기 패널의 리드 — 번호를 청하기 전에 지금의 사실부터 말한다. */
  openLead: string;
  /**
   * 번호가 어긋났을 때.
   * ⚠ 못 찾은 이유는 나누어 말하지 않는다(형식 오류와 못 찾음이 한 문장인 것은
   *   `store.findByCode` 주석이 정한 선이다 — 나누면 번호를 맞히려는 사람에게 힌트가 된다).
   */
  notFound: string;
  /**
   * 연달아 어긋난 뒤의 짧은 기다림. 가운데 초 숫자가 들어가므로 두 토막이다.
   * 기다림 자체는 그대로 둔다(무차별 대입을 늦추는 습관 — `LetterEntrance` 머리말).
   */
  wait: { lead: string; tail: string };
  /** 내가 만든 편지 목록 아래 — 그 목록이 무엇이고 어떻게 사라지는지. */
  listNote: string;
  /** 저장을 마치고 번호를 보여 주는 자리의 각주 — 이 번호를 다시 볼 수 있는가. */
  savedNote: string;
  /** 고쳐 쓸 때 번호 칸 아래. 비워 두면 번호가 그대로라는 사실. */
  codeKeepHint: string;
}

