/**
 * 비밀 편지 화면의 문구 — **이 배포에서 편지가 어디에 남는지**를 화면이 말한다 (§1.5o).
 *
 * ── 왜 문구를 한곳에 모았나 ──────────────────────────────────────────
 * 2026-08-17 감사가 P0 으로 올린 것은 버그가 아니라 **거짓말**이었다. 화면은 "번호를 아는
 * 분만 그 편지를 열 수 있어요" 라고 말했지만, 편지는 만든 사람의 브라우저에만 있어서
 * 받는 사람 기기에서는 올바른 번호를 넣어도 열리지 않았다. 실패하면 "한 글자씩 다시 봐
 * 주시겠어요?" 라며 오타를 의심시키고, 다섯 번 어긋나면 20초를 기다리게 했다.
 * 구조적으로 불가능한 일을 사용자 탓으로 돌린 셈이다.
 *
 * 그 문장들이 세 파일(입구·스튜디오·라우트 페이지)에 흩어져 있었기 때문에 한 자리를 고쳐도
 * 나머지가 옛말을 계속했다. 그래서 여기 모은다 — **화면마다 새로 짓지 않는다**
 * (`src/components/flowers/birth-copy.ts` 와 같은 장치다).
 *
 * ── 두 단계의 사실 ───────────────────────────────────────────────────
 * 이제 편지가 어디에 남는지는 **배포마다 다르다.** 그래서 문구도 두 벌이다.
 *
 *   `device` — Supabase env 가 비어 있는 배포. 편지는 그 브라우저에만 남고,
 *              번호를 건네받아도 다른 기기에서는 열리지 않는다.
 *   `server` — env 가 채워진 배포. 편지는 우리가 간직하고 번호로 어디서든 열린다.
 *              대신 **번호는 남기지 않는다**(서버에 해시만 있다) — 잃어버리면 우리도
 *              다시 알려드릴 수 없다는 사실이 이 벌에서 가장 무거운 한 줄이다.
 *
 * 어느 벌을 쓸지는 `LETTER_STORAGE_MODE`(빌드 타임 상수)가 정하고, **화면은 어느 쪽인지
 * 묻지 않는다** — 아래 이름 하나만 쓴다(`LETTER_STORAGE_NOTICE` …). 서버 렌더와 브라우저가
 * 같은 값을 읽으므로 하이드레이션이 어긋날 자리도 없다.
 *
 * 아래 문장들은 "이 배포의 사실"이지 서비스의 약속이 아니다(`/partners` 의
 * `NO_AFFILIATION` 과 같은 성격의 상수다). `tests/letters/device-notice.test.ts` 가 두 벌을
 * 각각 잰다 — 한 벌의 문장이 다른 벌로 새어 들어가면 그 자리에서 빨개진다.
 *
 * ⚠ 문구에 개발 어휘를 들이지 마라(§1.5d 해요체·이야기 톤). `브라우저 저장소` 까지가
 *   지금 쓰는 결이고, 그 아래(`localStorage`·`API`·`Supabase`)로는 내려가지 않는다.
 */

import { LETTER_STORAGE_MODE } from '@/lib/letters/supabase-store';

