/** 편지 번호 칸의 안내. 자릿수는 `LETTER_LIMITS` 가 정한다. */
export function letterCodeHint(min: number, max: number): string {
  return `영문과 숫자로 ${min}~${max}자. 편지를 열 때 이 번호를 적게 돼요.`;
}
