/**
 * `/stories?story={storyId}` — 이야기 한 편을 **주소로 여는 길**.
 *
 * ── 왜 필요한가 ──────────────────────────────────────────────────────
 * 아카이브의 상세는 페이지가 아니라 시트다(§1.5i). 그래서 지금까지 이야기 한 편에는
 * **가리킬 주소가 없었다** — 다른 화면이 "그 이야기로" 보내려면 `/stories` 목록까지만
 * 데려다 놓고 나머지는 사람이 찾아야 했다. 이 쿼리가 그 자리를 메운다:
 * 랜딩·도감·결과 어디서든 이 주소 한 줄이면 그 편이 펼쳐진 채로 선다.
 *
 * ── 왜 서버가 아니라 클라이언트가 읽나 ───────────────────────────────
 * 서버 컴포넌트에서 `searchParams` 를 읽으면 그 페이지는 요청 시점 렌더가 되고,
 * 정적 드롭 데모(`output: 'export'`)에서는 그 자체가 빌드 실패다(`/r` 이 같은 이유로
 * `location.search` 를 읽는다 — `components/flow/SharedPick.tsx` 머리말). 한 벌의 코드가
 * 두 배포에서 그대로 도는 쪽을 택한다.
 *
 * ⚠ **여기 오는 값은 남이 적은 값이다.** 주소창은 누구나 고쳐 쓸 수 있고, 그 문자열이
 *   그대로 화면 상태가 된다. 그래서 이 모듈이 하는 일의 절반은 **거절**이다 —
 *   생김새가 어긋나면 빈 문자열로 돌려보내고, 생김새가 맞아도 실재하는 이야기인지는
 *   부르는 쪽이 목록과 맞춰 본다(그 목록은 서버가 확정해 내려보낸 것이다).
 */

/** 쿼리 이름. 링크를 만드는 쪽과 읽는 쪽, 테스트가 **같은 값 하나**를 본다. */
export const STORY_PARAM = 'story';

/**
 * id 의 생김새 가드 — `content/stories.csv` 의 `story_id` 는 소문자·숫자·하이픈뿐이다
 * (`story-tulip-ottoman`). 실제 목록과 맞춰 보기 **전에** 여기서 한 번 거르는 이유는
 * 두 가지다: 목록에 없는 값이 로그·에러 메시지를 타고 흐르지 않게 하고, 길이 상한으로
 * 터무니없이 긴 질의가 366편 순회를 끌고 다니지 않게 한다.
 *
 * ⚠ 대문자·공백·슬래시·꺾쇠는 전부 여기서 막힌다. csv 에 그런 id 가 생기면 이 가드가
 *   먼저 깨지도록(=테스트가 먼저 빨개지도록) 실데이터 전수 검사를 함께 걸어 뒀다.
 */
const STORY_ID = /^[a-z0-9][a-z0-9-]{0,79}$/;

/**
 * `?story=…` 에서 이야기 id 를 꺼낸다. 없거나 생김새가 어긋나면 **빈 문자열**이다.
 *
 * 던지지 않는다 — 조작된 주소로 들어온 사람에게 화면이 깨져 보이는 것보다, 목록만
 * 조용히 서는 편이 낫다(§1.5i 의 "없는 길을 만들지 않는다" 와 같은 결).
 *
 * @param search `window.location.search` 그대로(`?a=1&story=x`). 앞의 `?` 는 있어도 없어도 된다.
 */
export function storyIdFromSearch(search: string): string {
  const wanted = new URLSearchParams(search).get(STORY_PARAM)?.trim() ?? '';
  return STORY_ID.test(wanted) ? wanted : '';
}

/**
 * 그 이야기로 보내는 주소 — **다른 화면이 쓰는 쪽**이다.
 *
 * 문자열을 손으로 이어 붙이지 않고 여기를 거치게 하는 이유는 쿼리 이름(`story`)을 한 곳에
 * 두기 위해서다. 화면마다 `?story=` 를 적어 두면 이름을 바꾸는 날 조용히 한둘이 남는다.
 */
export function storyHref(storyId: string): string {
  return `/stories?${STORY_PARAM}=${encodeURIComponent(storyId)}`;
}
