/**
 * 탄생화 사진이 **클라이언트로 건너갈 때의 모양** — 한 장을 걸고 크레딧을 밝히는 데 필요한 것만.
 *
 * ── 왜 따로 두는가 (`plates/view.ts` 선례) ───────────────────────────
 * 표 원본(`content/birth_photos.csv` → `Catalog.birthPhotos`)에는 취득 주소(`directUrl`)와
 * 종 동정 판정 근거(`speciesNote`)까지 들어 있다. 앞의 것은 재다운로드용이고 뒤의 것은
 * **편집·감사 기록**이라 둘 다 화면에 나갈 값이 아니다. 그런데 클라이언트 컴포넌트가
 * 표를 직접 뒤지면 그 280행이 통째로 브라우저 번들에 실린다(도판이 실제로 겪었던
 * 코드 리뷰 P1-7 이 그것이다).
 *
 * 그래서 경계를 이 파일이 긋는다:
 *   · `index.ts` = 경로·크레딧 조립 + 뷰 만들기(서버·스크립트 전용)
 *   · `view.ts`  = **타입 한 벌.** 클라이언트는 이 파일만 `import type` 한다.
 *
 * ⚠ 이 파일에 **값을 두지 마라.** 상수 하나만 들어와도 클라이언트 번들에 실린다.
 *
 * ── 라이선스가 타입에 들어 있는 이유 (Advisor 확정, 2026-08-16) ───────
 * 274장 중 218장이 CC BY / CC BY-SA 다. 우리가 화면에 거는 것은 원본이 아니라 **폭을 줄여
 * 다시 인코딩한 사본**이라 CC BY-SA 에서는 파생물에 해당한다. 그 의무는
 * **저작자 + 라이선스 라벨 + 원본(파일 페이지) 링크를 이미지 단위로 밝히면** 이행된다 —
 * 그래서 셋 중 하나라도 선택 필드가 아니다. 사진 위에 글자를 합성하지 않는 규칙도
 * 여기서 나온다(합성하면 그것부터가 또 다른 파생물이다).
 */

/** 사진 한 장을 걸고 출처를 밝히는 데 필요한 전부. 취득 주소·판정 근거는 여기 없다. */
export interface BirthPhotoView {
  /** 시트가 거는 자체 호스팅 사본(960px) — `/birth/{slug}.jpg`. */
  src: string;
  /** 목록 줄과 생일 찾기 카드가 거는 사본(320px) — `/birth/thumbs/{slug}.jpg`. */
  thumbSrc: string;
  /** 저작자. 라이선스 이행의 첫 칸이라 비어 있을 수 없다. */
  author: string;
  /** 라이선스 라벨 그대로(`CC BY-SA 4.0` · `CC0` · `Public domain`). */
  license: string;
  /** 위키미디어 파일 페이지 — 원본으로 돌아가는 링크이자 라이선스 증빙. */
  pageUrl: string;
  /**
   * 그 식물을 한 줄로 소개하는 문장(`family_line`). 사진 **아래** 캡션으로 나간다.
   * 사진 위에 얹지 않는다 — 합성 금지 규칙(위 머리말)과 §1.5d 톤 양쪽에 걸린다.
   * 미확보 행에는 없다.
   */
  familyLine?: string;
}
