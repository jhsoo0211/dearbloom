/** 이 조합에 갈아 끼울 변주가 있는가 — 화면의 `새로 받기` 를 세울지 정하는 값. */
export function hasDemoVariant(intent: string, tone: string): boolean {
  return DEMO_MESSAGE_VARIANTS[intent]?.[tone as ToneKey] !== undefined;
}

/**
 * 이 조합에서 `round` 번째로 내놓을 문장.
 *
 * **짝수 번째는 원장(csv)의 차례**라 여기서 만들지 않는다 — 부르는 쪽이 이미 들고 있는
 * 값이고(`buildTones` 가 누른 길이의 행을 고른다), 데모가 원장과 다른 첫 문장을 보여 줄
 * 이유가 없다. 그래서 `undefined` 를 돌려주고, 부르는 쪽이 지금 문장을 그대로 둔다.
 *
 * ⚠ 두 길이가 **같은 규칙**을 쓴다(2026-08-18 개정). 예전에는 `short` 만 손으로 쓴 두 벌을
 *   오갔는데, 그건 원장에 짧은 벌이 없어서였다. 지금은 원장이 길이마다 한 행씩 갖췄으므로
 *   길이마다 `원장 ↔ 변주` 로 도는 것이 규칙이 하나뿐이라 더 단순하고, 무엇보다 데모가
 *   원장을 반드시 한 번은 보여 준다(데모와 본배포의 첫 문장이 같아진다).
 *
 * 변주가 없는 조합(원장에 없던 마음·톤)도 `undefined` 다 — 없는 문장을 지어내지 않는다.
 */
export function demoVariantBody(
  intent: string,
  tone: string,
  length: MessageLength,
  round: number,
): string | undefined {
  const variant = DEMO_MESSAGE_VARIANTS[intent]?.[tone as ToneKey];
  if (!variant) return undefined;
  if (round % 2 === 0) return undefined;

  return length === 'short' ? variant.shortAlt : variant.mediumAlt;
}

/**
 * 분량 띠를 벗어난 변주 목록. 비어 있어야 한다.
 *
 * 화면의 길이 칸은 "140자 안" · "340자 안" 이라고 말한다. 데모의 예문이 그 말을 어기면
 * 데모가 보여 주는 것이 곧 거짓이 된다 — 하한도 함께 본다(짧게가 너무 짧으면 "짧게"가
 * 아니라 "부실"로 읽히고, 보통이 짧으면 이 개편이 하려던 일 자체가 무너진다).
 */
export function demoVariantsOutOfBand(): string[] {
  const out: string[] = [];
  const check = (label: string, text: string, band: { min: number; max: number }) => {
    if (text.length < band.min || text.length > band.max) {
      out.push(`${label}(${text.length}자, ${band.min}~${band.max}) ${text}`);
    }
  };

  for (const [intent, tones] of Object.entries(DEMO_MESSAGE_VARIANTS)) {
    for (const [tone, variant] of Object.entries(tones)) {
      check(`${intent}/${tone}/shortAlt`, variant.shortAlt, MESSAGE_LENGTH_CHARS.short);
      check(`${intent}/${tone}/mediumAlt`, variant.mediumAlt, MESSAGE_LENGTH_CHARS.medium);
    }
  }
  return out;
}
