/**
 * 생성 호출 **전에** 거는 차단문.
 *
 * 기획안 v2 의 후퇴 금지선: "심각 상황은 생성 호출 **전에** 차단".
 * 자해·폭력·응급처럼 꽃 멘트로 답할 일이 아닌 신호가 자유 서술에 섞여 있으면
 * 모델을 부르지 않고 준비된 템플릿으로 떨어뜨린다(생성한 문장이 그 상황에
 * 얹히는 것이 가장 나쁜 결과다).
 *
 * 설계 판단
 *  - **좁게 잡는다.** 조문·이별·다툼 같은 말은 꽃 선물의 정상 맥락이라 넣지 않는다.
 *    넓게 잡으면 진짜로 도움이 되는 자리를 통째로 막는다.
 *  - **원문은 이 파일 밖으로 나가지 않는다.** 판정 결과(boolean)만 돌려주고
 *    어떤 낱말이 걸렸는지도 반환하지 않는다(§1.5j: 로그·분석 어디에도 남기지 않는다).
 */

/** 심각 신호. 낱말이 아니라 부분 문자열로 본다(한국어는 조사가 붙는다). */
const BLOCKED_MARKERS = [
  '자살',
  '자해',
  '죽고 싶',
  '죽고싶',
  '목숨을 끊',
  '극단적 선택',
  '유서',
  '폭행',
  '학대',
  '성폭력',
  '스토킹',
  '납치',
  '협박',
  '살해',
  '응급실',
  '중환자실',
] as const;

/**
 * 이 텍스트들로 생성을 호출해도 되는가.
 * 하나라도 심각 신호에 걸리면 `true`(= 차단)를 돌려준다.
 */
export function isBlockedForGeneration(texts: readonly string[]): boolean {
  const joined = texts.join(' ').toLowerCase();
  if (joined.trim() === '') return false;
  return BLOCKED_MARKERS.some((marker) => joined.includes(marker));
}
