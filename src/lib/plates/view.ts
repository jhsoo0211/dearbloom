/**
 * 도판이 **클라이언트로 건너갈 때의 모양** — 액자 한 칸이 그리는 데 필요한 것만.
 *
 * ── 왜 따로 두는가 (코드 리뷰 P1-7) ─────────────────────────────────
 * `FLOWER_PLATES`(`./index.ts`)는 도판 32종의 취득 주소(`remoteSrc`)와 파일 페이지
 * (`pageUrl`)까지 들고 있는 **자산 관리용 표**다. 그런데 레인 헤더와 상세 시트가
 * `plateFor()` 를 클라이언트 컴포넌트에서 불렀기 때문에, 그 표가 통째로 브라우저 번들에
 * 실려 나갔다 — `/stories` 청크를 열면 `upload.wikimedia.org/...` 문자열 32벌이 그대로
 * 들어 있었다. 화면은 그중 **한 줄도 쓰지 않는다.**
 *
 * 그래서 경계를 이 파일이 긋는다:
 *   · `index.ts` = 표 원본 + 서버·스크립트 전용 함수(`FLOWER_PLATES` · `plateSrc` …)
 *   · `view.ts`  = **타입 한 벌**. 클라이언트는 이 파일만 `import type` 한다.
 * 값(뷰)은 서버 컴포넌트가 `plateViewFor()` 로 만들어 props 로 내려보낸다 —
 * 클라이언트가 표를 뒤질 일이 없으니 표가 번들에 들어갈 이유도 사라진다.
 *
 * ⚠ 이 파일에 **값을 두지 마라.** 상수 하나만 들어와도 클라이언트 번들에 실린다.
 */

/** 액자 한 칸이 그리는 데 필요한 전부. 취득 주소·파일 페이지는 여기 없다. */
export interface PlateView {
  /** `content/flowers.csv` 의 id. 액자의 `data-plate` 와 React key 로 쓴다. */
  flowerId: string;
  /**
   * 그 자리의 **표시 크기에 맞춰 이미 고른** 주소(`plateSrc(plate, width)` 의 결과).
   * 화면에서 폭을 다시 고르지 않는다 — 고르는 일은 서버에서 한 번 끝난다.
   */
  src: string;
  /** 도판이 실제로 무엇을 그렸는지. 장식으로 걸 때는 화면이 빈 alt 로 덮는다. */
  alt: string;
  /** 종이 다르거나 판면에 손댄 도판의 정직한 한 줄. 대부분의 꽃에는 없다. */
  note?: string;
  /** 시트 각주 한 줄 — `도판: {작가} · {작품명} {번호}, {연도} / {기관}`. */
  sourceLine: string;
}
